/**
 * @brief A GLSL (1.20) function generated by OpenColorIO, and the lookup tables it samples.
 * The function has the signature "vec4 <functionName>(vec4 inPixel)".
 **/
struct OCIOViewerShader
{
    struct Texture
    {
        std::string samplerName; // name of the sampler uniform in shaderText
        unsigned width = 0;
        unsigned height = 0;     // 1D tables are given as width x 1 2D textures
        unsigned depth = 0;      // 0 for a 2D texture, the cube size for a 3D LUT
        int channels = 3;        // 1 (red) or 3 (rgb)
        bool linearInterpolation = true;
        std::vector<float> values;
    };

    std::string functionName;
    std::string shaderText;
    std::vector<Texture> textures;
};

/**
 * @brief The OpenColorIO display/view transform applied by a viewer, from the config's
 * scene_linear role (Natron's working space) to a display.
 * Immutable and thread-safe once created; get it from OCIOViewerProcess::getProcessor().
 **/
class OCIOViewerProcessor
{
public:
    virtual ~OCIOViewerProcessor() {}

    // Identifies the transform (config, display, view): use it in cache keys.
    virtual const std::string& getCacheID() const = 0;

    // Transforms numPixels packed RGBA float pixels in place (alpha is unchanged).
    virtual void applyRGBA(float* pixels, long numPixels) const = 0;

    // The same transform as GLSL 1.20, for the viewer's fragment shader.
    virtual const OCIOViewerShader& getShader() const = 0;
};

typedef std::shared_ptr<const OCIOViewerProcessor> OCIOViewerProcessorPtr;

/**
 * @brief Access to the OpenColorIO config used by Natron (the "OCIO" environment variable,
 * which Natron sets from Preferences > Color Management) for viewer display transforms.
 * All functions are thread-safe. When Natron is built without OpenColorIO (NATRON_USE_OCIO
 * undefined), isAvailable() returns false and the other functions return empty results.
 **/
class OCIOViewerProcess
{
public:
    static bool isAvailable();

    /// (Re)loads the config if the OCIO environment variable changed.
    /// Returns false and sets error if no valid config could be loaded.
    static bool loadCurrentConfig(std::string* error = 0);

    /// Name of the loaded config (empty if none).
    static std::string getConfigName();

    /// True if the current config is one built into OpenColorIO (an "ocio://..." URI), e.g. the ACES
    /// configs offered in the Preferences. New viewers then start on its default display/view.
    static bool isBuiltinConfig();

    static std::vector<std::string> getDisplays();
    static std::string getDefaultDisplay();
    static std::vector<std::string> getViews(const std::string& display);
    static std::string getDefaultView(const std::string& display);

    /// Returns the processor for display/view in the current config (cached), or a null
    /// pointer and an error message if the transform cannot be built.
    static OCIOViewerProcessorPtr getProcessor(const std::string& display,
                                               const std::string& view,
                                               std::string* error = 0);

    /// The looks of the current config (e.g. "ACES 1.3 Reference Gamut Compression").
    static std::vector<std::string> getLooks();

    /// The same with a look applied before the view transform (the "looks override" of OCIO's viewing
    /// pipeline: it replaces the looks of the view; empty: the view as defined by the config).
    static OCIOViewerProcessorPtr getProcessor(const std::string& display,
                                               const std::string& view,
                                               const std::string& look,
                                               std::string* error = 0);
};

